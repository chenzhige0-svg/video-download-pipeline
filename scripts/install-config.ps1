[CmdletBinding()]
param(
    [string]$Root = (Split-Path -Parent $PSScriptRoot),
    [string]$Destination
)

$ErrorActionPreference = 'Stop'

$rootPath = (Resolve-Path -LiteralPath $Root).Path.TrimEnd('\')
$template = Join-Path $PSScriptRoot '..\config\yt-dlp.conf.template'
if (-not (Test-Path -LiteralPath $template)) {
    throw "找不到配置模板：$template"
}

if (-not $Destination) {
    $scoopPersist = 'C:\scoop\persist\yt-dlp'
    if (Test-Path -LiteralPath $scoopPersist) {
        $Destination = Join-Path $scoopPersist 'yt-dlp.conf'
    }
    else {
        $Destination = Join-Path $env:APPDATA 'yt-dlp\config'
    }
}

$destDir = Split-Path -Parent $Destination
if (-not (Test-Path -LiteralPath $destDir)) {
    New-Item -ItemType Directory -Path $destDir -Force | Out-Null
}

if (Test-Path -LiteralPath $Destination) {
    $backup = "$Destination.bak-$(Get-Date -Format 'yyyyMMdd-HHmmss')"
    Copy-Item -LiteralPath $Destination -Destination $backup
    Write-Host "已备份原配置：$backup"
}

$rootForConfig = $rootPath.Replace('\', '/')
$content = Get-Content -LiteralPath $template -Raw -Encoding UTF8
$content = $content.Replace('{{ROOT}}', $rootForConfig)

$utf8NoBom = New-Object System.Text.UTF8Encoding($false)
[System.IO.File]::WriteAllText($Destination, $content, $utf8NoBom)

foreach ($name in @('.cookies', '.tmp', 'bilibili', 'douyin', 'tiktok', 'weibo', 'xiaohongshu', 'youtube')) {
    $path = Join-Path $rootPath $name
    if (-not (Test-Path -LiteralPath $path)) {
        New-Item -ItemType Directory -Path $path -Force | Out-Null
    }
}

$allCookies = Join-Path $rootPath '.cookies\all.txt'
if (-not (Test-Path -LiteralPath $allCookies)) {
    $header = "# Netscape HTTP Cookie File`r`n# generated by scripts/cookie-export.py`r`n`r`n"
    [System.IO.File]::WriteAllText($allCookies, $header, $utf8NoBom)
}

Write-Host "配置已写入：$Destination"
Write-Host "下载根目录：$rootPath"
Write-Host "下一步：运行 scripts\open-chrome-profile.cmd 登录，再运行 python scripts\cookie-export.py"
